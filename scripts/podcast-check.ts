import assert from "node:assert/strict";
import { approvePodcast, newPodcast, recordPodcast, revise, revoke, startHandoff } from "../src/modules/publisher/podcast/model";

const now = Date.parse("2026-11-28T00:00:00Z");
const meta = { title: "合成タイトル", description: "合成説明文", number: "12", plannedAt: "2026-11-29T13:00" };
const cover = { filename: "cover.png", blob: new Blob(["fixture"], { type: "image/png" }), revision: "cover" };
const digest = "a".repeat(64);
const row = newPodcast("episode", meta, now);
assert.throws(() => approvePodcast(row, "担当", "audio", digest, now), /画像/);
revise(row, meta, cover, now);
approvePodcast(row, "担当", "audio", digest, now);
revise(row, { ...meta, title: "改訂" }, cover, now + 1);
assert.equal(row.approval, undefined);
approvePodcast(row, "担当", "audio", digest, now + 2);
assert.throws(() => startHandoff(row, [], "replacement", digest, now + 3), /改めて承認/);
revoke(row, now + 4);
approvePodcast(row, "担当", "audio", digest, now + 5);
startHandoff(row, [], "audio", digest, now + 6);
assert.throws(() => startHandoff(row, [], "audio", digest, now + 7), /改めて承認/);
recordPodcast(row, [], "unknown", "照合保留", "", now + 8);
assert.throws(() => approvePodcast(row, "担当", "audio", digest, now + 9), /再承認/);
const other = newPodcast("new-id", { ...meta, number: "012" }, now);
revise(other, other.metadata, cover, now);
approvePodcast(other, "担当", "other", "b".repeat(64), now + 1);
assert.throws(() => startHandoff(other, [row], "other", "b".repeat(64), now + 10), /同じ音源または/);
recordPodcast(row, [], "absent", "既存の一覧で下書き・予約なし", "", now + 11);
assert.equal(row.approval, undefined);
approvePodcast(row, "担当", "audio", digest, now + 12);
startHandoff(row, [], "audio", digest, now + 13);
recordPodcast(row, [], "spotify-draft", "既存下書きあり", "", now + 14);
assert.throws(() => startHandoff(row, [], "audio", digest, now + 15), /改めて承認/);
recordPodcast(row, [], "scheduled", "既存番組の予約を確認", "abcdefghijk", now + 16);
assert.throws(() => recordPodcast(row, [], "spotify-draft", "古い情報", "", now + 17), /状態/);
recordPodcast(row, [], "published", "公開確認", "abcdefghijk", now + 18);
assert.equal(row.status, "published");
console.log("OK: podcast approval, revision, cross-episode duplicate guard, unknown recovery, and published history");
