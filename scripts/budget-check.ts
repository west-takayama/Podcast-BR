import assert from "node:assert/strict";
import { beginRequest, BudgetError, emptyBudget, finishRequest, summarize } from "../src/modules/budget/ledger";
import { estimatedCost, japanDay, japanMonth, maximumCost, rateFor, scale } from "../src/modules/budget/pricing";
import { recordActual } from "../src/modules/budget/store";

const at = Date.parse("2026-11-30T14:59:59.999Z");
assert.equal(japanMonth(at), "2026-11");
assert.equal(japanDay(at + 1), "2026-12-01");
assert.equal(japanMonth(at + 1), "2026-12");
const exchange = { usdJpy: 100, taxPercent: 10, fxMarginPercent: 5 };
const rate = rateFor("gemini-2.5-flash", at)!;
const counts = { inputTokens: 1_000_000, audioTokens: 500_000, outputTokens: 10_000, thinkingTokens: 10_000, cachedTokens: 100_000, cachedAudioTokens: 50_000 };
const cost = estimatedCost(rate, counts, exchange, true)!;
// 450k standard text, 450k audio, 50k each cached, 20k output and thinking -> USD 0.6415.
assert.ok(Math.abs(cost / scale - 74.09325) < 0.000002);
assert.equal(estimatedCost(rate, { inputTokens: 42 }, exchange, true), undefined);
assert.ok(maximumCost(rate, exchange, true) > maximumCost(rate, exchange, false));
assert.equal(rateFor("gemini-3.8-flash", Date.parse("2026-12-31T14:59:59Z"))?.output, 3.75);
assert.equal(rateFor("gemini-3.8-flash", Date.parse("2026-12-31T15:00:00Z"))?.output, 7.50);
assert.equal(rateFor("model-unknown", at), undefined);

const state = emptyBudget();
state.settings = { ...state.settings, ...exchange, mode: "postpaid" };
const request = { purpose: "captions", model: "gemini-2.5-flash", attempt: 1, hasAudio: true };
state.operating.push({ id: "other", label: "hosting", at, amount: 1_700 * scale });
assert.equal(summarize(state, at).warned, true);
const pending = beginRequest(state, { ...request, requestKey: "same" }, "one", at);
assert.throws(() => beginRequest(state, request, "two", at), BudgetError);
assert.equal(summarize(state, at + 1).pending, pending.reserved);
finishRequest(pending, {}, { elapsedMs: 100, error: "TimeoutError" });
assert.equal(pending.state, "unknown");
assert.equal(pending.estimate, undefined);
assert.equal(summarize(state, at + 1).unknown, pending.reserved);
recordActual(state, "2026-11", 50, at, at + 700_000);
assert.equal(summarize(state, at + 1).unknown, 0);
assert.equal(summarize(state, at).total, 1_750 * scale);
state.operating.length = 0;
const retry = beginRequest(state, { ...request, attempt: 2 }, "retry", at);
finishRequest(retry, counts, { elapsedMs: 22, status: 200, billing: "input-only", error: "ProviderStopped" });
assert.ok(retry.estimate! < cost);
const refused = beginRequest(state, request, "refused", at);
finishRequest(refused, {}, { elapsedMs: 10, status: 503 });
assert.equal(refused.estimate, 0);
assert.equal(refused.success, false);
assert.throws(() => beginRequest(state, { ...request, attempt: 5 }, "cap", at), /試行上限/);
assert.throws(() => beginRequest(state, { ...request, model: "different" }, "bad", at), /見積もれない/);
assert.throws(() => beginRequest(state, { ...request, usesTools: true }, "tool", at), /見積もれない/);
state.settings = { ...state.settings, mode: "prepaid" };
assert.throws(() => beginRequest(state, request, "empty", at), /チャージ残高/);
state.settings.balance = { at, amount: 500 * scale };
const funded = beginRequest(state, request, "funded", at + 1);
assert.equal(summarize(state, at + 1).balanceRemaining, 500 * scale - funded.reserved);
state.settings = { ...state.settings, mode: "free" };
const free = beginRequest(state, request, "free", at);
finishRequest(free, {}, { elapsedMs: 1, status: 200 });
assert.equal(free.estimate, undefined);
const freeKnown = beginRequest(state, request, "free-known", at);
finishRequest(freeKnown, counts, { elapsedMs: 1, status: 200 });
assert.equal(freeKnown.estimate, 0);
console.log("OK: modality/cache rates, thinking, FX/tax, JST rollover, estimates, calls and reservations");
